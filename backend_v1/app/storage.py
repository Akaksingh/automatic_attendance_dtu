"""Configurable local filesystem or S3-compatible object storage."""
from __future__ import annotations

from io import BytesIO
from pathlib import Path

from .config import settings


class Storage:
    def __init__(self) -> None:
        self.backend = settings.storage_backend.lower()
        if self.backend == "s3":
            import boto3
            self.client = boto3.client(
                "s3",
                region_name=settings.storage_region,
                endpoint_url=settings.storage_endpoint_url,
                aws_access_key_id=settings.storage_access_key_id,
                aws_secret_access_key=settings.storage_secret_access_key,
            )
            if not settings.storage_bucket:
                raise RuntimeError("STORAGE_BUCKET is required when STORAGE_BACKEND=s3")
        elif self.backend != "local":
            raise RuntimeError("STORAGE_BACKEND must be local or s3")

    def put_bytes(self, key: str, content: bytes, content_type: str) -> None:
        if self.backend == "s3":
            self.client.put_object(Bucket=settings.storage_bucket, Key=key, Body=content, ContentType=content_type)
            return
        path = self._local_path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)

    def get_bytes(self, key: str) -> bytes:
        if self.backend == "s3":
            return self.client.get_object(Bucket=settings.storage_bucket, Key=key)["Body"].read()
        return self._local_path(key).read_bytes()

    def delete(self, key: str) -> None:
        if self.backend == "s3":
            self.client.delete_object(Bucket=settings.storage_bucket, Key=key)
            return
        self._local_path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        if self.backend == "s3":
            try:
                self.client.head_object(Bucket=settings.storage_bucket, Key=key)
                return True
            except self.client.exceptions.ClientError:
                return False
        return self._local_path(key).is_file()

    @staticmethod
    def _local_path(key: str) -> Path:
        # Storage keys are generated by the server; reject unsafe keys anyway.
        path = (Path(settings.data_dir) / key).resolve()
        root = Path(settings.data_dir).resolve()
        if root not in path.parents:
            raise ValueError("Unsafe storage key")
        return path


storage = Storage()
